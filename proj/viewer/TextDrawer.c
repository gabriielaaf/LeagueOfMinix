static const uint8_t unknownGlyph[TEXT_CHAR_H] = {
    0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04
};

static const uint8_t *textGetGlyph(char c) {
    if (c >= 'a' && c <= 'z') {
        c = c - 'a' + 'A';
    }

    for (unsigned int i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++) {
        if (glyphs[i].c == c) {
            return glyphs[i].rows;
        }
    }

    return unknownGlyph;
}

static void textDrawPixelBlock(int x, int y, uint32_t color, uint8_t scale) {
    if (x < 0 || y < 0) {
        return;
    }

    if (scale <= 1) {
        vg_draw_pixel((uint16_t)x, (uint16_t)y, color);
    }
    else {
        vg_draw_rectangle((uint16_t)x, (uint16_t)y, scale, scale, color);
    }
}

void textDrawChar(char c,
                  int x,
                  int y,
                  uint32_t color,
                  uint8_t scale) {
    if (scale == 0) {
        scale = 1;
    }

    if (c == ' ') {
        return;
    }

    const uint8_t *glyph = textGetGlyph(c);

    for (int row = 0; row < TEXT_CHAR_H; row++) {
        for (int col = 0; col < TEXT_CHAR_W; col++) {
            if (glyph[row] & (1 << (TEXT_CHAR_W - 1 - col))) {
                textDrawPixelBlock(
                    x + col * scale,
                    y + row * scale,
                    color,
                    scale
                );
            }
        }
    }
}

void textDrawString(const char *text,
                    int x,
                    int y,
                    uint32_t color,
                    uint8_t scale,
                    uint8_t spacing) {
    if (text == NULL) {
        return;
    }

    if (scale == 0) {
        scale = 1;
    }

    int start_x = x;
    int cursor_x = x;
    int cursor_y = y;

    for (int i = 0; text[i] != '\0'; i++) {
        if (text[i] == '\n') {
            cursor_x = start_x;
            cursor_y += (TEXT_CHAR_H + spacing) * scale;
            continue;
        }

        textDrawChar(text[i], cursor_x, cursor_y, color, scale);

        cursor_x += (TEXT_CHAR_W + spacing) * scale;
    }
}

void textDrawInt(int value,
                 int x,
                 int y,
                 uint32_t color,
                 uint8_t scale,
                 uint8_t spacing) {
    char buffer[12];
    int index = 0;
    bool negative = false;

    if (value == 0) {
        textDrawChar('0', x, y, color, scale);
        return;
    }

    if (value < 0) {
        negative = true;
        value = -value;
    }

    while (value > 0 && index < 10) {
        buffer[index++] = '0' + (value % 10);
        value /= 10;
    }

    if (negative) {
        buffer[index++] = '-';
    }

    int cursor_x = x;

    for (int i = index - 1; i >= 0; i--) {
        textDrawChar(buffer[i], cursor_x, y, color, scale);
        cursor_x += (TEXT_CHAR_W + spacing) * scale;
    }
}
